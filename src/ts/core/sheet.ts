// Report downloads as formatted Excel files (.xlsx), written here without a library.
// The sheet: a title band (report, who, when, filters), bold heading row that stays in view with filter arrows, columns sized
// to fit, dates and pesos stored as real values (so they sort and add up), tinted rows for the ones that need action,
// a totals row, and a landscape page that prints one page wide with the headings repeated.
// An .xlsx is a zip of XML parts; the zip is "stored" (not compressed), which every spreadsheet app opens.
import { csvDateTime } from "./format";

export type RowTone = "" | "danger" | "warning";

export interface SheetReport {
  title: string;                       // "Loans"
  file: string;                        // "loans": becomes cmu-library_loans_2026-10-29_1430.xlsx
  header: string[];
  rows: unknown[][];
  filters?: [string, string][];        // [["From", "2026-10-01"], ["Status", "borrowed"]]; empty ones are left out
  by?: string;                         // who downloaded it
  totals?: string[];                   // columns added up in a Total row
  tone?: (row: unknown[]) => RowTone;  // tints a row that needs action (overdue, fully borrowed)
}

// ---------------------------------------------------------------- the file name and the title band
const slug = (text: string) => text.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 24);

export function sheetInfo(report: SheetReport, at = new Date().toISOString()): { name: string; meta: [string, string][] } {
  const shown = (report.filters ?? []).filter(([, v]) => v);
  const meta: [string, string][] = [
    ["Report", report.title],
    ["Generated", `${csvDateTime(at)} (Philippine time)`],
    ...(report.by ? [["Generated by", report.by] as [string, string]] : []),
    ["Filters", shown.length ? shown.map(([k, v]) => `${k}: ${v}`).join("; ") : "None (everything)"],
    ["Rows", String(report.rows.length)],
  ];
  const stamp = csvDateTime(at).replace(" ", "_").replace(":", "");
  const tags = shown.map(([k, v]) => `${slug(k)}-${slug(v)}`).filter((t) => !t.endsWith("-"));
  return { name: ["cmu-library", report.file, ...tags, stamp].join("_") + ".xlsx", meta };
}

// ---------------------------------------------------------------- what kind of value each column holds
type Kind = "text" | "number" | "money" | "date" | "datetime";
const DATE = /^\d{4}-\d{2}-\d{2}$/;
const DATETIME = /^\d{4}-\d{2}-\d{2} \d{2}:\d{2}$/;
const isMoney = (heading: string) => /\((php|₱)\)|fine|amount/i.test(heading);

function kindOf(heading: string, values: unknown[]): Kind {
  const filled = values.filter((v) => v !== "" && v !== null && v !== undefined);
  if (!filled.length) return "text";
  if (isMoney(heading) && filled.every((v) => !Number.isNaN(Number(v)))) return "money";
  if (filled.every((v) => typeof v === "number")) return "number";
  if (filled.every((v) => typeof v === "string" && DATE.test(v))) return "date";
  if (filled.every((v) => typeof v === "string" && (DATETIME.test(v) || DATE.test(v)))) return "datetime";
  return "text";
}

// Excel counts days from 1899-12-30; the strings are already Philippine time, so they are read as they are written
const serial = (text: string) => {
  const [y, m, d, h = "0", mi = "0"] = text.split(/[- :]/);
  return Date.UTC(+y, +m - 1, +d, +h, +mi) / 86400000 + 25569;
};

// ---------------------------------------------------------------- styles
// colours follow the Library Blue theme: crest blue, gold, and the soft status tints
const BLUE = "FF0A2E9C", NAVY = "FF0B1F5C", LINE = "FFD3DCEC", ZEBRA = "FFF5F8FD", META = "FFE6EDF8", TOTAL = "FFDFE8FB", DANGER = "FFFBE0E5", WARNING = "FFFDEAB9", SOFT = "FF5A6A8A", INK = "FF1D2B4A";
const FILLS = ["", ZEBRA, DANGER, WARNING];          // body row fills: plain, zebra, danger, warning
const TONE_FILL = { "": 0, danger: 2, warning: 3 } as const;
const FORMATS: Record<Kind, number> = { text: 0, number: 3, money: 4, date: 165, datetime: 164 };
const KINDS: Kind[] = ["text", "number", "money", "date", "datetime"];

// cellXfs: 0 default, 1 title, 2 meta, 3 heading, then body styles (kind x fill), then total styles (kind)
const BODY = 4;
const bodyStyle = (kind: Kind, fill: number) => BODY + KINDS.indexOf(kind) * FILLS.length + fill;
const TOTAL_BASE = BODY + KINDS.length * FILLS.length;
const totalStyle = (kind: Kind) => TOTAL_BASE + KINDS.indexOf(kind);

function stylesXml(): string {
  const fill = (rgb: string) => `<fill><patternFill patternType="solid"><fgColor rgb="${rgb}"/><bgColor indexed="64"/></patternFill></fill>`;
  // fills 0 and 1 are reserved by Excel; 2 title, 3 heading, 4 meta, 5 total, 6.. body fills
  const fills = [`<fill><patternFill patternType="none"/></fill>`, `<fill><patternFill patternType="gray125"/></fill>`, fill(BLUE), fill(NAVY), fill(META), fill(TOTAL), ...FILLS.slice(1).map(fill)];
  const bodyFill = (i: number) => (i === 0 ? 0 : 5 + i);
  const xf = (font: number, fillId: number, border: number, numFmt: number, align = "") =>
    `<xf numFmtId="${numFmt}" fontId="${font}" fillId="${fillId}" borderId="${border}" applyNumberFormat="1" applyFont="1" applyFill="1" applyBorder="1"${align ? ` applyAlignment="1"><alignment ${align}/></xf>` : "/>"}`;
  const xfs = [
    xf(0, 0, 0, 0),
    xf(1, 2, 0, 0, `vertical="center" indent="1"`),
    xf(2, 4, 0, 0, `vertical="center" indent="1"`),
    xf(3, 3, 1, 0, `vertical="center" wrapText="1"`),
    ...KINDS.flatMap((k) => FILLS.map((_, i) => xf(4, bodyFill(i), 1, FORMATS[k], `vertical="top"${k === "text" ? ` wrapText="1"` : ""}`))),
    ...KINDS.map((k) => xf(5, 5, 2, FORMATS[k], `vertical="center"`)),
  ];
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<styleSheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">
<numFmts count="2"><numFmt numFmtId="164" formatCode="yyyy-mm-dd hh:mm"/><numFmt numFmtId="165" formatCode="yyyy-mm-dd"/></numFmts>
<fonts count="6">
<font><sz val="11"/><color rgb="${INK}"/><name val="Calibri"/><family val="2"/></font>
<font><b/><sz val="15"/><color rgb="FFFFFFFF"/><name val="Calibri"/><family val="2"/></font>
<font><i/><sz val="10"/><color rgb="${SOFT}"/><name val="Calibri"/><family val="2"/></font>
<font><b/><sz val="11"/><color rgb="FFFFFFFF"/><name val="Calibri"/><family val="2"/></font>
<font><sz val="11"/><color rgb="${INK}"/><name val="Calibri"/><family val="2"/></font>
<font><b/><sz val="11"/><color rgb="${INK}"/><name val="Calibri"/><family val="2"/></font>
</fonts>
<fills count="${fills.length}">${fills.join("")}</fills>
<borders count="3">
<border><left/><right/><top/><bottom/><diagonal/></border>
<border><left style="thin"><color rgb="${LINE}"/></left><right style="thin"><color rgb="${LINE}"/></right><top style="thin"><color rgb="${LINE}"/></top><bottom style="thin"><color rgb="${LINE}"/></bottom><diagonal/></border>
<border><left style="thin"><color rgb="${LINE}"/></left><right style="thin"><color rgb="${LINE}"/></right><top style="medium"><color rgb="${BLUE}"/></top><bottom style="medium"><color rgb="${BLUE}"/></bottom><diagonal/></border>
</borders>
<cellStyleXfs count="1"><xf numFmtId="0" fontId="0" fillId="0" borderId="0"/></cellStyleXfs>
<cellXfs count="${xfs.length}">${xfs.join("")}</cellXfs>
<cellStyles count="1"><cellStyle name="Normal" xfId="0" builtinId="0"/></cellStyles>
</styleSheet>`;
}

// ---------------------------------------------------------------- the sheet
const esc = (text: string) => text.replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const col = (i: number): string => (i >= 26 ? col(Math.floor(i / 26) - 1) : "") + String.fromCharCode(65 + (i % 26));
const text = (ref: string, style: number, value: string) => `<c r="${ref}" s="${style}" t="inlineStr"><is><t xml:space="preserve">${esc(value)}</t></is></c>`;
const num = (ref: string, style: number, value: number) => `<c r="${ref}" s="${style}"><v>${value}</v></c>`;

const HEAD = 5; // the heading row; rows 1-3 are the title band, row 4 is a gap

function sheetXml(report: SheetReport, meta: [string, string][]): { xml: string; filterRef: string; last: string } {
  const { header, rows } = report;
  const last = col(Math.max(header.length, 1) - 1);
  const kinds = header.map((h, i) => kindOf(h, rows.map((r) => r[i])));

  // widths from the longest value in each column (dates have a fixed width), kept between 8 and 48 characters
  const widths = header.map((h, i) => {
    if (kinds[i] === "datetime") return 17;
    if (kinds[i] === "date") return 12;
    const longest = Math.max(h.length, ...rows.slice(0, 500).map((r) => String(r[i] ?? "").length));
    return Math.min(Math.max(longest + 3, 8), 48);
  });

  const xmlRows: string[] = [];
  const get = (key: string) => meta.find(([k]) => k === key)?.[1] ?? "";
  const titleLine = `CMU Library  ·  ${report.title}`;
  const whoLine = [`Generated ${get("Generated")}`, get("Generated by") && `by ${get("Generated by")}`].filter(Boolean).join("  ·  ");
  const filterLine = `Filters: ${get("Filters")}  ·  ${rows.length} row${rows.length === 1 ? "" : "s"}`;
  xmlRows.push(`<row r="1" ht="30" customHeight="1">${text("A1", 1, titleLine)}${header.slice(1).map((_, i) => `<c r="${col(i + 1)}1" s="1"/>`).join("")}</row>`);
  xmlRows.push(`<row r="2" ht="18" customHeight="1">${text("A2", 2, whoLine)}${header.slice(1).map((_, i) => `<c r="${col(i + 1)}2" s="2"/>`).join("")}</row>`);
  xmlRows.push(`<row r="3" ht="18" customHeight="1">${text("A3", 2, filterLine)}${header.slice(1).map((_, i) => `<c r="${col(i + 1)}3" s="2"/>`).join("")}</row>`);
  xmlRows.push(`<row r="${HEAD}" ht="24" customHeight="1">${header.map((h, i) => text(`${col(i)}${HEAD}`, 3, h)).join("")}</row>`);

  rows.forEach((row, r) => {
    const at = HEAD + 1 + r;
    const tone = report.tone?.(row) ?? "";
    const fill = tone ? TONE_FILL[tone] : r % 2 ? 1 : 0;
    const cells = header.map((_, i) => {
      const ref = `${col(i)}${at}`;
      const v = row[i];
      const style = bodyStyle(kinds[i], fill);
      if (v === "" || v === null || v === undefined) return `<c r="${ref}" s="${style}"/>`;
      if (kinds[i] === "number" || kinds[i] === "money") return num(ref, style, Number(v));
      if (kinds[i] === "date" || kinds[i] === "datetime") return num(ref, style, serial(String(v)));
      return text(ref, style, String(v));
    });
    xmlRows.push(`<row r="${at}">${cells.join("")}</row>`);
  });

  const end = HEAD + rows.length;
  const merges = [`A1:${last}1`, `A2:${last}2`, `A3:${last}3`];
  if (!rows.length) {
    xmlRows.push(`<row r="${HEAD + 1}" ht="22" customHeight="1">${text(`A${HEAD + 1}`, 2, "No rows for these filters.")}</row>`);
    merges.push(`A${HEAD + 1}:${last}${HEAD + 1}`);
  } else if (report.totals?.length) {
    // a Total row with live SUM formulas, so edits in the sheet still add up
    const at = end + 1;
    const cells = header.map((h, i) => {
      const ref = `${col(i)}${at}`;
      const style = totalStyle(kinds[i] === "money" || kinds[i] === "number" ? kinds[i] : "text");
      if (i === 0) return text(ref, totalStyle("text"), "Total");
      if (!report.totals!.includes(h)) return `<c r="${ref}" s="${style}"/>`;
      const sum = rows.reduce((s, r) => s + (Number(r[i]) || 0), 0);
      return `<c r="${ref}" s="${style}"><f>SUM(${col(i)}${HEAD + 1}:${col(i)}${end})</f><v>${Math.round(sum * 100) / 100}</v></c>`;
    });
    xmlRows.push(`<row r="${at}" ht="22" customHeight="1">${cells.join("")}</row>`);
  }

  const filterRef = `A${HEAD}:${last}${Math.max(end, HEAD)}`;
  const lastRow = rows.length ? end + (report.totals?.length ? 1 : 0) : HEAD + 1;
  const xml = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
<sheetPr><pageSetUpPr fitToPage="1"/></sheetPr>
<dimension ref="A1:${last}${lastRow}"/>
<sheetViews><sheetView workbookViewId="0" showGridLines="0"><pane ySplit="${HEAD}" topLeftCell="A${HEAD + 1}" activePane="bottomLeft" state="frozen"/><selection pane="bottomLeft" activeCell="A${HEAD + 1}" sqref="A${HEAD + 1}"/></sheetView></sheetViews>
<sheetFormatPr defaultRowHeight="16"/>
<cols>${widths.map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join("")}</cols>
<sheetData>${xmlRows.join("")}</sheetData>
${rows.length ? `<autoFilter ref="${filterRef}"/>` : ""}
<mergeCells count="${merges.length}">${merges.map((m) => `<mergeCell ref="${m}"/>`).join("")}</mergeCells>
<pageMargins left="0.4" right="0.4" top="0.5" bottom="0.6" header="0.3" footer="0.3"/>
<pageSetup paperSize="9" orientation="landscape" fitToWidth="1" fitToHeight="0"/>
<headerFooter><oddFooter>&amp;L${esc(`CMU Library · ${report.title}`)}&amp;RPage &amp;P of &amp;N</oddFooter></headerFooter>
</worksheet>`;
  return { xml, filterRef, last };
}

// ---------------------------------------------------------------- the workbook and the zip around it
export function buildXlsx(report: SheetReport, at = new Date().toISOString()): { name: string; bytes: Uint8Array<ArrayBuffer> } {
  const info = sheetInfo(report, at);
  const tab = report.title.replace(/[[\]:*?/\\]/g, " ").slice(0, 31) || "Report";
  const sheet = sheetXml(report, info.meta);
  const abs = (ref: string) => ref.replace(/([A-Z]+)(\d+)/g, "$$$1$$$2");
  const quoted = `'${tab.replace(/'/g, "''")}'`;
  const names = [
    report.rows.length ? `<definedName name="_xlnm._FilterDatabase" localSheetId="0" hidden="1">${esc(quoted)}!${abs(sheet.filterRef)}</definedName>` : "",
    `<definedName name="_xlnm.Print_Titles" localSheetId="0">${esc(quoted)}!$${HEAD}:$${HEAD}</definedName>`,
  ].join("");
  const created = new Date(at).toISOString().replace(/\.\d+Z$/, "Z");
  const files: [string, string][] = [
    ["[Content_Types].xml", `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/><Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/><Override PartName="/xl/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.styles+xml"/><Override PartName="/docProps/core.xml" ContentType="application/vnd.openxmlformats-package.core-properties+xml"/></Types>`],
    ["_rels/.rels", `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/><Relationship Id="rId2" Type="http://schemas.openxmlformats.org/package/2006/relationships/metadata/core-properties" Target="docProps/core.xml"/></Relationships>`],
    ["docProps/core.xml", `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<cp:coreProperties xmlns:cp="http://schemas.openxmlformats.org/package/2006/metadata/core-properties" xmlns:dc="http://purl.org/dc/elements/1.1/" xmlns:dcterms="http://purl.org/dc/terms/" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"><dc:title>${esc(`CMU Library · ${report.title}`)}</dc:title><dc:creator>${esc(report.by || "CMU Library Explorer")}</dc:creator><dcterms:created xsi:type="dcterms:W3CDTF">${created}</dcterms:created></cp:coreProperties>`],
    ["xl/workbook.xml", `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><bookViews><workbookView/></bookViews><sheets><sheet name="${esc(tab)}" sheetId="1" r:id="rId1"/></sheets><definedNames>${names}</definedNames></workbook>`],
    ["xl/_rels/workbook.xml.rels", `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/><Relationship Id="rId2" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/></Relationships>`],
    ["xl/styles.xml", stylesXml()],
    ["xl/worksheets/sheet1.xml", sheet.xml],
  ];
  return { name: info.name, bytes: zip(files) };
}

const CRC_TABLE = (() => {
  const table = new Uint32Array(256);
  for (let n = 0; n < 256; n++) { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; table[n] = c >>> 0; }
  return table;
})();
const crc32 = (bytes: Uint8Array) => { let c = 0xffffffff; for (const b of bytes) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8); return (c ^ 0xffffffff) >>> 0; };

export function zip(files: [string, string][]): Uint8Array<ArrayBuffer> {
  const encoder = new TextEncoder();
  const chunks: Uint8Array[] = [];
  const central: Uint8Array[] = [];
  let offset = 0;
  for (const [path, content] of files) {
    const name = encoder.encode(path);
    const data = encoder.encode(content);
    const crc = crc32(data);
    const local = new Uint8Array(30 + name.length);
    const l = new DataView(local.buffer);
    l.setUint32(0, 0x04034b50, true); l.setUint16(4, 20, true); l.setUint16(6, 0x0800, true); l.setUint16(8, 0, true);
    l.setUint16(10, 0, true); l.setUint16(12, 0x21, true); l.setUint32(14, crc, true); l.setUint32(18, data.length, true); l.setUint32(22, data.length, true);
    l.setUint16(26, name.length, true); l.setUint16(28, 0, true); local.set(name, 30);
    const entry = new Uint8Array(46 + name.length);
    const c = new DataView(entry.buffer);
    c.setUint32(0, 0x02014b50, true); c.setUint16(4, 20, true); c.setUint16(6, 20, true); c.setUint16(8, 0x0800, true); c.setUint16(10, 0, true);
    c.setUint16(12, 0, true); c.setUint16(14, 0x21, true); c.setUint32(16, crc, true); c.setUint32(20, data.length, true); c.setUint32(24, data.length, true);
    c.setUint16(28, name.length, true); c.setUint32(42, offset, true); entry.set(name, 46);
    chunks.push(local, data);
    central.push(entry);
    offset += local.length + data.length;
  }
  const size = central.reduce((s, e) => s + e.length, 0);
  const end = new Uint8Array(22);
  const e = new DataView(end.buffer);
  e.setUint32(0, 0x06054b50, true); e.setUint16(8, files.length, true); e.setUint16(10, files.length, true); e.setUint32(12, size, true); e.setUint32(16, offset, true);
  const out = new Uint8Array(offset + size + 22);
  let at = 0;
  for (const part of [...chunks, ...central, end]) { out.set(part, at); at += part.length; }
  return out;
}

export function downloadSheet(report: SheetReport, at?: string): void {
  const { name, bytes } = buildXlsx(report, at);
  const link = document.createElement("a");
  link.href = URL.createObjectURL(new Blob([bytes], { type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet" }));
  link.download = name;
  link.click();
  setTimeout(() => URL.revokeObjectURL(link.href), 1000);
}
