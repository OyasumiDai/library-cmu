import { build } from "esbuild";
import os from "node:os";
import path from "node:path";
import { pathToFileURL } from "node:url";
const out = path.join(os.tmpdir(), "cmu-lockout.mjs");
const store = new Map();
globalThis.localStorage = { getItem: (k) => store.get(k) ?? null, setItem: (k, v) => store.set(k, v) };
await build({ entryPoints: ["src/ts/core/lockout.ts"], outfile: out, format: "esm", bundle: true, logLevel: "silent" });
const L = await import(pathToFileURL(out).href);
await build({ entryPoints: ["src/ts/core/password.ts"], outfile: out.replace("lockout", "password"), format: "esm", bundle: true, logLevel: "silent" });
const P = await import(pathToFileURL(out.replace("lockout", "password")).href);
const t0 = 1_000_000;
const ok = (c, m) => { if (!c) { console.error("FAIL:", m); process.exitCode = 1; } };
const a = "ann@school.edu", b = "ben@school.edu";
ok(L.recordFailure(a, t0) === 0 && L.recordFailure(a, t0) === 0, "two wrong tries do not lock");
ok(L.triesLeft(a) === 1, "one try left");
ok(L.recordFailure(a, t0) === 60 && L.secondsLocked(a, t0) === 60, "the third wrong try locks for 1 minute");
ok(L.secondsLocked(b, t0) === 0, "another email is not locked");
ok(L.secondsLocked(a, t0 + 61000) === 0, "the lock ends after a minute");
const waits = [];
for (let round = 0; round < 7; round++) { L.recordFailure(a, t0 + 99999); L.recordFailure(a, t0 + 99999); waits.push(L.recordFailure(a, t0 + 99999) / 60); }
ok(JSON.stringify(waits) === JSON.stringify([3, 5, 10, 15, 30, 60, 60]), "repeated lockouts grow 3, 5, 10, 15, 30, 60 minutes and stay at 60: " + waits);
L.clearFailures(a);
ok(L.secondsLocked(a, t0 + 99999) === 0 && L.triesLeft(a) === 3, "a correct sign-in clears everything");
ok(L.countdown(125) === "2:05", "the countdown is mm:ss");
ok(P.checkPassword("password123").problems.length > 0 && P.checkPassword("short").problems.length > 0, "common and short passwords are refused");
ok(P.checkPassword("cyrus2024!X", "cyrus").problems.length > 0, "a password containing the name is refused");
ok(P.checkPassword("Tr4vel-Quietly-Home").level >= 3 && P.checkPassword("Tr4vel-Quietly-Home").problems.length === 0, "a good password is accepted and rated well");
ok(P.checkPassword("aaaaaaaa").level <= 1, "repeated letters are weak");
if (!process.exitCode) console.log("PASS: lockout schedule and password rules");
